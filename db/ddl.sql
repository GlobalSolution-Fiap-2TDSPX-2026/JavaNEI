-- DDL das tabelas do projeto NEI (Near Earth Impact)
-- Baseado nas entidades JPA: Asteroid, CloseApproach, User

CREATE TABLE TB_ASTEROID (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NASA_ID VARCHAR2(255),
    NAME VARCHAR2(255),
    ESTIMATED_DIAMETER_MIN_KM NUMBER,
    ESTIMATED_DIAMETER_MAX_KM NUMBER,
    ABSOLUTE_MAGNITUDE NUMBER,
    IS_POTENTIALLY_DANGEROUS NUMBER(1)
);

CREATE TABLE TB_CLOSE_APPROACH (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ASTEROID_ID NUMBER,
    APPROACH_DATE DATE,
    MISS_DISTANCE_KM NUMBER,
    RELATIVE_VELOCITY_KM_H NUMBER,
    ORBITING_BODY VARCHAR2(255),
    RISK_LEVEL NUMBER,
    CONSTRAINT FK_CLOSE_APPROACH_ASTEROID FOREIGN KEY (ASTEROID_ID) REFERENCES TB_ASTEROID(ID)
);

CREATE TABLE TB_USER (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255),
    EMAIL VARCHAR2(255),
    USERNAME VARCHAR2(255),
    PASSWORD VARCHAR2(255)
);
